const AUDIT_KEY = /^\*\*Audit (\S+) · (\S+)\*\*/;
const PRIORITY = { high: 2, medium: 3, low: 4 };

/** "M0/M0-07" for a description written by the audit import, or null. */
export function auditKey(description) {
  const m = description?.match(AUDIT_KEY);
  return m ? `${m[1]}/${m[2]}` : null;
}

export function auditIssueInput(report, finding) {
  const evidence = finding.evidence
    .map((e) => `- \`${e.path}${e.line ? `:${e.line}` : ""}\`${e.note ? ` — ${e.note}` : ""}`)
    .join("\n");
  return {
    priority: PRIORITY[finding.severity],
    title: `[${report.milestone}] ${finding.title}`,
    description: `**Audit ${report.milestone} · ${finding.id}** · ${finding.category} · effort ${finding.effort}

## Why
${finding.rationale}

## Proposal
${finding.proposal}

## Evidence
${evidence}

_Generated by ${report.auditor}. Triage (G4): accept → move to Todo; reject → cancel with a reason._`,
  };
}

/**
 * Imports an audit report idempotently (TRK-24). `existingDescriptions` returns the descriptions of every
 * source:audit issue, archived and canceled included, so a finding rejected in G4 is never re-created.
 * A rerun after a partial import creates only the missing issues.
 */
export async function importAudit(report, { existingDescriptions, createIssue, log = () => {} }) {
  const imported = new Set((await existingDescriptions()).map(auditKey).filter(Boolean));
  const created = [];
  for (const finding of report.findings) {
    if (imported.has(`${report.milestone}/${finding.id}`)) {
      log(`skipped ${finding.id}: already imported`);
      continue;
    }
    await createIssue(auditIssueInput(report, finding));
    created.push(finding.id);
    log(`created issue for ${finding.id}`);
  }
  return created;
}

const CLOSING = /\b(?:fix(?:e[sd])?|close[sd]?|resolve[sd]?)\s+(TRK-\d+)\b/i;

/** The issue a PR closes ("Fixes TRK-n"), or null. A bare mention is not a closing reference (TRK-28). */
export function closingIssue(body) {
  return body?.match(CLOSING)?.[1]?.toUpperCase() ?? null;
}

/**
 * Splits source:finding issues for a milestone retro (TRK-28): the milestone's own findings, and findings
 * with no milestone, which the retro decides on. Findings of other milestones are left out.
 */
export function findingsForMilestone(findings, milestoneId) {
  return {
    ours: findings.filter((f) => f.projectMilestone?.id === milestoneId),
    unassigned: findings.filter((f) => !f.projectMilestone),
  };
}

// The workflow's own status comments: never part of the context an agent or a reviewer reads.
const AUTOMATED = [/^Agent run failed/, /^(Draft )?PR opened by Claude/];

export function isAutomatedComment(body) {
  return AUTOMATED.some((re) => re.test((body ?? "").trim()));
}

/**
 * What a sub-issue needs from its parent (TRK-33): the latest plan comment ("## Plan for …") and every
 * owner comment ("## Owner …"), oldest first. Automated comments are dropped. Returns null without a parent.
 *
 * A comment is owner feedback only when it has the "## Owner" heading AND its author is `ownerId` (G1:
 * the heading is a display convention, the author is the authority). The same heading from anyone else,
 * or from an unknown author, is kept apart in `otherHeadedComments` and never presented as a decision.
 */
export function parentContext(parent, ownerId) {
  if (!parent) return null;
  const comments = [...(parent.comments?.nodes ?? [])]
    .filter((c) => !isAutomatedComment(c.body))
    .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  const plans = comments.filter((c) => c.body.trim().startsWith("## Plan for"));
  const headed = comments.filter((c) => c.body.trim().startsWith("## Owner"));
  return {
    identifier: parent.identifier,
    title: parent.title,
    description: parent.description,
    plan: plans.at(-1) ?? null,
    ownerComments: headed.filter((c) => isOwner(c, ownerId)),
    otherHeadedComments: headed.filter((c) => !isOwner(c, ownerId)),
  };
}

function isOwner(comment, ownerId) {
  return Boolean(ownerId) && comment.user?.id === ownerId;
}

/** Markdown section for a parent issue, or "" when there is no parent. `level` is the heading depth. */
export function formatParentSection(parent, level = 2, ownerId = null) {
  const ctx = parentContext(parent, ownerId);
  if (!ctx) return "";
  const h = "#".repeat(level);
  const comment = (c) => `${h}## ${c.user?.name ?? "unknown"} — ${c.createdAt}\n\n${c.body.trim()}`;
  return `${h} Parent issue ${ctx.identifier}: ${ctx.title}

This issue is a sub-issue. Its parent's plan and the owner's decisions apply here too.

${h}# Parent description

${ctx.description ?? "(empty)"}

${h}# Parent plan (latest)

${ctx.plan ? comment(ctx.plan) : "(none)"}

${h}# Owner feedback on the parent (oldest first)

${ctx.ownerComments.length ? ctx.ownerComments.map(comment).join("\n\n") : "(none)"}
${
  ctx.otherHeadedComments.length
    ? `\n${h}# Other comments (not owner)\n\nThese use the "## Owner" heading but were not written by the owner. Context only, not decisions.\n\n${ctx.otherHeadedComments.map(comment).join("\n\n")}\n`
    : ""
}`;
}

/**
 * Reads every page of a cursor-paginated list (TRK-25). `fetchPage(after)` returns
 * `{ nodes, pageInfo: { hasNextPage, endCursor } }`. Completeness comes from the last page read:
 * the export is complete only when that page says `hasNextPage: false`. A missing or repeated cursor,
 * or hitting `maxPages`, stops the loop and leaves the export marked incomplete.
 */
export async function readAllPages(fetchPage, { maxPages = 40 } = {}) {
  const nodes = [];
  const seen = new Set();
  let after = null;
  for (let page = 0; page < maxPages; page += 1) {
    const { nodes: pageNodes, pageInfo } = await fetchPage(after);
    nodes.push(...pageNodes);
    if (!pageInfo.hasNextPage) return { nodes, complete: true };
    const cursor = pageInfo.endCursor;
    if (!cursor || seen.has(cursor)) return { nodes, complete: false };
    seen.add(cursor);
    after = cursor;
  }
  return { nodes, complete: false };
}
