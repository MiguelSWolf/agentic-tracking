#!/usr/bin/env node
// ADR index for humans and agents.
//
//   node scripts/adr-index.mjs           regenerate docs/adr/README.md
//   node scripts/adr-index.mjs --check   exit 1 if the index is out of date (CI)
//   node scripts/adr-index.mjs --next    print the next free ADR number (e.g. 0014)
//
// Every ADR file is docs/adr/NNNN-<kebab-slug>.md and starts with:
//   # ADR-NNNN: <decision in one sentence>
//
//   - Status: Proposed | Accepted | Superseded by ADR-XXXX | Deprecated
//   - Date: YYYY-MM-DD
//   - Tags: comma, separated, keywords
//   - Supersedes: ADR-XXXX            (optional)

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'docs/adr';
const INDEX = join(DIR, 'README.md');
const FILE_RE = /^(\d{4})-[a-z0-9-]+\.md$/;

function parse(file) {
  const text = readFileSync(join(DIR, file), 'utf8');
  const title = text.match(/^# ADR-(\d{4}): (.+)$/m);
  const field = (name) => text.match(new RegExp(`^- ${name}: (.+)$`, 'm'))?.[1]?.trim() ?? '';
  if (!title) throw new Error(`${file}: missing "# ADR-NNNN: <title>" heading`);
  if (title[1] !== file.slice(0, 4)) throw new Error(`${file}: heading number ${title[1]} does not match file name`);
  for (const f of ['Status', 'Date', 'Tags']) {
    if (!field(f)) throw new Error(`${file}: missing "- ${f}:" line`);
  }
  return {
    id: `ADR-${title[1]}`,
    file,
    title: title[2].trim(),
    status: field('Status'),
    date: field('Date'),
    tags: field('Tags'),
    supersedes: field('Supersedes'),
  };
}

const adrs = readdirSync(DIR)
  .filter((f) => FILE_RE.test(f))
  .sort()
  .map(parse);

if (process.argv.includes('--next')) {
  const last = adrs.length ? Number(adrs.at(-1).id.slice(4)) : 0;
  console.log(String(last + 1).padStart(4, '0'));
  process.exit(0);
}

const rows = adrs
  .map((a) => {
    const sup = a.supersedes ? ` (supersedes ${a.supersedes})` : '';
    return `| [${a.id}](${a.file}) | ${a.title}${sup} | ${a.status} | ${a.date} | ${a.tags} |`;
  })
  .join('\n');

const index = `# Architecture Decision Records

<!-- Generated by scripts/adr-index.mjs. Do not edit by hand: run \`pnpm adr:index\`. -->

Every significant decision is recorded here. **Agents read this index before planning any issue** and cite the ADRs a change touches. To add or supersede a decision, use the \`write-adr\` skill (\`.agents/skills/write-adr/\`).

- Only \`Accepted\` ADRs are in force. \`Superseded\` ones are kept for history and point to their replacement.
- Search by tag: \`grep -i "<tag>" docs/adr/README.md\`.

| ADR | Decision | Status | Date | Tags |
| --- | --- | --- | --- | --- |
${rows}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
  if (current !== index) {
    console.error('docs/adr/README.md is out of date. Run: pnpm adr:index');
    process.exit(1);
  }
  console.log(`ADR index up to date (${adrs.length} ADRs).`);
  process.exit(0);
}

writeFileSync(INDEX, index);
console.log(`Wrote ${INDEX} (${adrs.length} ADRs).`);
