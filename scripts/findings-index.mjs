#!/usr/bin/env node
// Findings index: process and tooling gaps found while running the agentic loop.
// The milestone retro reads these files and records a decision for each one.
//
//   node scripts/findings-index.mjs              regenerate every docs/retros/<milestone>/findings/README.md
//   node scripts/findings-index.mjs --check      exit 1 if any index is out of date (CI)
//   node scripts/findings-index.mjs --next m0    print the next free finding id for a milestone (e.g. F-013)
//
// Every finding file is docs/retros/<milestone>/findings/F-NNN-<kebab-slug>.md and starts with:
//   # F-NNN: <what went wrong, in one sentence>
//
//   - Status: open | in progress (TRK-n) | fixed (#PR) | accepted
//   - Area: <gate, CI, agent context, review, code standards, …>
//   - Source: agent | workflow | owner
//   - Found: YYYY-MM-DD
//   - Evidence: <PR, run or issue links>

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "docs/retros";
const FILE_RE = /^F-(\d{3})-[a-z0-9-]+\.md$/;
const SOURCES = new Set(["agent", "workflow", "owner"]);

function parse(dir, file) {
  const text = readFileSync(join(dir, file), "utf8");
  const title = text.match(/^# F-(\d{3}): (.+)$/m);
  const field = (name) => text.match(new RegExp(`^- ${name}: (.+)$`, "m"))?.[1]?.trim() ?? "";
  if (!title) throw new Error(`${dir}/${file}: missing "# F-NNN: <title>" heading`);
  if (title[1] !== file.slice(2, 5)) {
    throw new Error(`${dir}/${file}: heading number ${title[1]} does not match file name`);
  }
  for (const f of ["Status", "Area", "Source", "Found", "Evidence"]) {
    if (!field(f)) throw new Error(`${dir}/${file}: missing "- ${f}:" line`);
  }
  if (!SOURCES.has(field("Source"))) {
    throw new Error(`${dir}/${file}: Source must be one of ${[...SOURCES].join(", ")}`);
  }
  return {
    id: `F-${title[1]}`,
    file,
    title: title[2].trim(),
    status: field("Status"),
    area: field("Area"),
    source: field("Source"),
    found: field("Found"),
  };
}

function milestones() {
  if (!existsSync(ROOT)) return [];
  return readdirSync(ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(ROOT, d.name, "findings")))
    .map((d) => d.name)
    .sort();
}

function load(milestone) {
  const dir = join(ROOT, milestone, "findings");
  return readdirSync(dir)
    .filter((f) => FILE_RE.test(f))
    .sort()
    .map((f) => parse(dir, f));
}

function render(milestone, findings) {
  const open = findings.filter((f) => !/^(fixed|accepted)/.test(f.status)).length;
  const rows = findings
    .map((f) => `| [${f.id}](${f.file}) | ${f.title} | ${f.area} | ${f.source} | ${f.status} |`)
    .join("\n");
  return `# ${milestone.toUpperCase()} findings

<!-- Generated by scripts/findings-index.mjs. Do not edit by hand: run \`pnpm findings:index\`. -->

Process and tooling gaps found while running the agentic loop in ${milestone.toUpperCase()}. They are recorded as soon as they are noticed, by agents (in the same PR), by the workflows (a Linear issue labelled \`finding\`, imported by the retro) or by the owner. The milestone retro records a decision for each one. See [docs/workflow/findings.md](../../../workflow/findings.md).

**${findings.length} findings, ${open} still open.**

| ID | Finding | Area | Source | Status |
| --- | --- | --- | --- | --- |
${rows}
`;
}

const args = process.argv.slice(2);

if (args[0] === "--next") {
  const milestone = args[1];
  if (!milestone) {
    console.error("Usage: findings-index.mjs --next <milestone>");
    process.exit(1);
  }
  const dir = join(ROOT, milestone, "findings");
  const ids = existsSync(dir) ? load(milestone).map((f) => Number(f.id.slice(2))) : [];
  const next = (ids.length ? Math.max(...ids) : 0) + 1;
  console.log(`F-${String(next).padStart(3, "0")}`);
  process.exit(0);
}

const check = args.includes("--check");
let stale = 0;
let total = 0;
for (const milestone of milestones()) {
  const findings = load(milestone);
  total += findings.length;
  const index = join(ROOT, milestone, "findings", "README.md");
  const content = render(milestone, findings);
  if (check) {
    const current = existsSync(index) ? readFileSync(index, "utf8") : "";
    if (current !== content) {
      console.error(`${index} is out of date. Run: pnpm findings:index`);
      stale += 1;
    }
  } else {
    writeFileSync(index, content);
    console.log(`Wrote ${index} (${findings.length} findings).`);
  }
}

if (check) {
  if (stale > 0) process.exit(1);
  console.log(`Findings indexes up to date (${total} findings).`);
}
